'use strict';

/**
 * 错词判重键（**唯一实现**）。
 * ---------------------------------------------------------------------------
 * 口径：去全角括号批注 `（……）` → 折叠空白 → 去首尾 → 转小写。
 *
 * 为什么必须收敛到一处：
 *   库内唯一键是 `uk_mistakes_text(student_id, wrong_text)`，建在**原始列**上；
 *   而契约要求「规范化后判重」。二者不同源 ⇒ 规范化只能在**应用层**完成，
 *   于是「谁来做规范化」就成了正确性关键。历史上 `db/migration/sync_mistakes.js`
 *   内联了一份实现；写接口若另写一份，任何一处微调都会让两条写入路径
 *   对「同一行」判断不同 —— 这正是 DQ1（同一条错被拆成两行）的成因类型。
 *
 * ⚠️ **只用于「找同一行」，不用于落库** —— 落库一律写原始文本（错词本原样）。
 *    因此本函数**不得**把结果当作 `wrong_text` 写入数据库。
 */

function normKey(text) {
  return String(text == null ? '' : text)
    .replace(/（[^）]*）/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

module.exports = { normKey };
